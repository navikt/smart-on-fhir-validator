const TEST_PDF_BASE64 = Buffer.from(TEST_PDF_CONTENT).toString('base64')
const TEST_PDF_BYTES = Buffer.from(TEST_PDF_CONTENT)

function testId(kind: string): string {
    return `smart-on-fhir-validator-${kind}-${randomUUID()}`
}

function grantedScopesText(launch: LaunchContext): string {
    return launch.grantedScopes.length > 0 ? launch.grantedScopes.join(', ') : 'none'
}

/**
 * A granted scope permits writing `resourceType` when it is a clinical scope for that resource
 * (or `*`) whose CRUDS permission includes create, update or delete. Both SMART v1 (`write`) and
 * v2 (`cud`/`cruds`) forms are accepted, since EHRs may grant either.
 */
function grantsWriteScope(launch: LaunchContext, resourceType: string): boolean {
    return launch.grantedScopes.some((raw) => {
        const scope = parseScope(raw)
        if (scope.kind !== 'clinical') return false
        if (scope.resource !== '*' && scope.resource !== resourceType) return false
        return /[cud]/.test(scope.cruds)
    })
}

function asRecord(body: unknown): Record<string, unknown> | null {
    return body != null && typeof body === 'object' ? (body as Record<string, unknown>) : null
}

function asTyped<T extends { resourceType: string }>(
    body: unknown,
    resourceType: T['resourceType'],
): T | null {
    const record = asRecord(body)
    return record?.resourceType === resourceType ? (record as unknown as T) : null
}

function operationOutcomeSummary(body: unknown): string | null {
    const outcome = asTyped<OperationOutcome>(body, 'OperationOutcome')
    if (!outcome?.issue) return null
    return outcome.issue.map((issue) => issue.diagnostics ?? issue.details?.text ?? issue.code).join('; ')
}

function extractCreatedId(response: RecordedResponse): string | null {
    const bodyId = asRecord(response.body)?.id
    if (typeof bodyId === 'string' && bodyId.length > 0) return bodyId

    const location = response.headers.get('Location') ?? response.headers.get('Content-Location')
    if (!location) return null

    const match = /\/([^/?]+?)(?:\/_history\/[^/?]+)?\/?(?:\?.*)?$/.exec(location)
    return match?.[1] ?? null
}

function createOutcomeValidations(response: RecordedResponse, resourceType: string): Validation[] {
    const validations: Validation[] = []
    const url = response.exchange.request.url

    if (response.status === 201) {
        validations.push(validation(`POST ${url} correctly returned 201 Created`, 'OK'))
    } else if (response.status === 200) {
        validations.push(
            validation(
                `POST ${url} returned 200 OK instead of 201 Created for a new ${resourceType}. FHIR R4 requires a successful create to return 201.`,
                'WARNING',
                [hl7Refs.fhirHttpCreate],
            ),
        )
    } else {
        const outcomeSummary = operationOutcomeSummary(response.body)
        const transport =
            response.status === 0 ? ` (transport failure: ${response.exchange.error ?? 'unknown'})` : ''
        validations.push(
            validation(
                `POST ${url} failed to create the ${resourceType} with status ${response.status}${transport}. ${outcomeSummary ? `Server returned: ${outcomeSummary}` : 'No OperationOutcome was returned to explain the failure.'}`,
                'ERROR',
                [hl7Refs.fhirHttpCreate],
            ),
        )
        return validations
    }

    const location = response.headers.get('Location') ?? response.headers.get('Content-Location')
    if (!location) {
        validations.push(
            validation(
                `POST ${url} did not include a Location or Content-Location header pointing at the created ${resourceType}`,
                'WARNING',
                [hl7Refs.fhirHttpCreate],
            ),
        )
    } else {
        validations.push(validation(`Response included a Location header: "${location}"`, 'OK'))
    }

    return validations
}

/**
 * FHIR R4 permits either 201 or 200 for a `PUT` update-as-create, so neither is a WARNING, and no
 * `Location` header is required since the client chose the URL.
 *
 * @see https://hl7.org/fhir/R4/http.html#upsert
 */
function upsertOutcomeValidations(
    response: RecordedResponse,
    resourceType: string,
    attempt: 'first' | 'second',
): Validation[] {
    const url = response.exchange.request.url
    const attemptLabel = attempt === 'first' ? 'First' : 'Second'

    if (response.status === 201) {
        if (attempt === 'first') {
            return [
                validation(
                    `${attemptLabel} PUT ${url} returned 201 Created, a legal update-as-create response per FHIR R4.`,
                    'OK',
                    [hl7Refs.fhirHttpUpsert],
                ),
            ]
        }

        return [
            validation(
                `${attemptLabel} PUT ${url} (same client-assigned id, repeated) returned 201 Created again. Per FHIR R4 upsert semantics, a repeated PUT to an id that already exists should return 200 OK; returning 201 a second time may mean the server created a second, distinct resource instead of updating the first, which risks the sykmelding being filed twice in the patient's journal.`,
                'WARNING',
                [hl7Refs.fhirHttpUpsert, navRefs.adr01],
            ),
        ]
    }

    if (response.status === 200) {
        return [
            validation(
                `${attemptLabel} PUT ${url} returned 200 OK, a legal update-as-create response per FHIR R4.`,
                'OK',
                [hl7Refs.fhirHttpUpsert],
            ),
        ]
    }

    const outcomeSummary = operationOutcomeSummary(response.body)
    const transport =
        response.status === 0 ? ` (transport failure: ${response.exchange.error ?? 'unknown'})` : ''
    return [
        validation(
            `${attemptLabel} PUT ${url} failed to upsert the ${resourceType} with status ${response.status}${transport}. ${outcomeSummary ? `Server returned: ${outcomeSummary}` : 'No OperationOutcome was returned to explain the failure.'}`,
            'ERROR',
            [hl7Refs.fhirHttpUpsert],
        ),
    ]
}

/**
 * Nav's write-back relies on a second PUT of the same client-assigned id being an update rather
 * than a second create, so a retry cannot double-file a sykmelding in the patient's journal.
 */
function idempotencyValidation(
    first: RecordedResponse,
    second: RecordedResponse,
    resourceType: string,
    id: string,
): Validation {
    const firstId = asRecord(first.body)?.id
    const secondId = asRecord(second.body)?.id
    const firstMatches = firstId === undefined || firstId === id
    const secondMatches = secondId === undefined || secondId === id

    if (firstMatches && secondMatches) {
        return validation(
            `Repeating PUT ${second.exchange.request.url} with the same client-assigned id "${id}" did not produce a different resource id: both responses are consistent with a single ${resourceType}/${id}. This is the idempotency property Nav's write-back depends on (ADR01): a retried write after a network blip must not double-file the sykmelding.`,
            'OK',
            [navRefs.adr01],
        )
    }

    return validation(
        `Repeating PUT ${second.exchange.request.url} with the same client-assigned id "${id}" produced a different resource id (first response id: "${String(firstId)}", second response id: "${String(secondId)}"). A compliant PUT-as-upsert must always operate on ${resourceType}/${id}; returning a different id risks the sykmelding being filed twice in the patient's journal.`,
        'ERROR',
        [hl7Refs.fhirHttpUpsert, navRefs.adr01],
    )
}

/**
 * A 403 is the correct outcome when the write scope was never granted: an EHR that rejects an
 * unauthorised write is conformant, not failing.
 */
function scopeEnforcementOutcome(
    probe: ResourceProbe,
    response: RecordedResponse,
    resourceType: string,
    launch: LaunchContext,
    method: string = 'POST',
): ProbeOutcome {
    const url = response.exchange.request.url
    const validations: Validation[] = []

    if (response.status === 403) {
        validations.push(
            validation(
                `No write scope for ${resourceType} was granted (granted scopes: ${grantedScopesText(launch)}). ${method} ${url} was correctly rejected with 403 Forbidden. This is the expected behaviour for a write attempted outside the granted scopes.`,
                'OK',
                [hl7Refs.smartLaunch],
            ),
        )
    } else if (response.ok) {
        validations.push(
            validation(
                `No write scope for ${resourceType} was granted (granted scopes: ${grantedScopesText(launch)}), yet ${method} ${url} succeeded with status ${response.status}. A SMART-conformant server must enforce granted scopes and reject writes outside them with 403 Forbidden.`,
                'ERROR',
                [hl7Refs.smartLaunch],
            ),
        )
    } else {
        validations.push(
            validation(
                `No write scope for ${resourceType} was granted (granted scopes: ${grantedScopesText(launch)}). ${method} ${url} was rejected with status ${response.status} rather than 403 Forbidden. 403 is the status a SMART server should use to signal insufficient authorization for an otherwise well-formed request.`,
                'WARNING',
                [hl7Refs.smartLaunch],
            ),
        )
    }

    return { probeId: probe.id, label: probe.label, exchangeId: response.exchange.id, validations }
}

function testResourceNotice(resourceType: string, id: string): Validation {
    return validation(
        `Created a test ${resourceType} in the vendor's EHR with id "${id}". This is a real record written to their system by this validator. Delete or clean up "${resourceType}/${id}" after reviewing this report.`,
        'INFO',
    )
}

function containsResource(bundle: Bundle | null, resourceType: string, id: string): boolean {
    if (bundle == null) return false
    return (bundle.entry ?? []).some((entry) => {
        const resource = entry.resource as { resourceType?: string; id?: string } | undefined
        return resource?.resourceType === resourceType && resource.id === id
    })
}

/** Verifies `resourceType` can be found from launch context alone, without configured ids. */
async function searchableValidations(
    context: ProbeContext,
    resourceType: string,
    createdId: string,
    params: Record<string, string>,
    paramDescription: string,
): Promise<Validation[]> {
    const response = await context.fhir.search(resourceType, params)
    const url = response.exchange.request.url
    const validations: Validation[] = []

    if (!response.ok) {
        validations.push(
            validation(
                `GET ${url} failed with status ${response.status}. A written ${resourceType} must be findable by ${paramDescription} alone.`,
                'ERROR',
                [hl7Refs.fhirHttpSearch],
            ),
        )
        return validations
    }

    const bundle = asTyped<Bundle>(response.body, 'Bundle')
    if (bundle == null) {
        validations.push(
            validation(`GET ${url} did not return a FHIR Bundle`, 'ERROR', [hl7Refs.fhirHttpSearch]),
        )
        return validations
    }

    if (bundle.type !== 'searchset') {
        validations.push(
            validation(
                `GET ${url} returned a Bundle of type "${bundle.type}", expected "searchset"`,
                'ERROR',
                [hl7Refs.search],
            ),
        )
    }

    if (containsResource(bundle, resourceType, createdId)) {
        validations.push(
            validation(
                `The created ${resourceType} was found via GET ${url} (searchable by ${paramDescription})`,
                'OK',
            ),
        )
    } else {
        validations.push(
            validation(
                `The created ${resourceType} ("${resourceType}/${createdId}") was NOT found via GET ${url}. It must be discoverable by ${paramDescription} alone so it can be located without a server-assigned id.`,
                'ERROR',
                [hl7Refs.documentReference],
            ),
        )
    }

    return validations
}

/**
 * Runs one Binary upload mechanism (FHIR-JSON or raw body) through the same create-then-read-back
 * checks. Reports `succeeded: false` when the mechanism cannot be verified end-to-end, so the
 * caller can decide whether the other mechanism covers Nav's "Må" requirement for Binary.
 */
async function binaryMechanismValidations(
    fhir: FhirClient,
    response: RecordedResponse,
    mechanismLabel: string,
): Promise<{ validations: Validation[]; succeeded: boolean }> {
    const validations = createOutcomeValidations(response, 'Binary')

    if (!response.ok) {
        return { validations, succeeded: false }
    }

    const createdId = extractCreatedId(response)
    if (createdId == null) {
        validations.push(
            validation(
                `Could not determine the id of the Binary created via the ${mechanismLabel} mechanism from the response body or Location header, so round-trip could not be verified.`,
                'ERROR',
                [hl7Refs.binary],
            ),
        )
        return { validations, succeeded: false }
    }

    validations.push(testResourceNotice('Binary', createdId))
    validations.push(validation(`Binary upload via the ${mechanismLabel} mechanism succeeded.`, 'OK'))

    const created = asTyped<Binary>(response.body, 'Binary')
    if (created) {
        validations.push(...validateBinary(created, { id: createdId, contentType: 'application/pdf' }))
    }

    const readBack = await fhir.read('Binary', createdId)
    if (!readBack.ok) {
        validations.push(
            validation(
                `GET ${readBack.exchange.request.url} (round-trip read-back for the ${mechanismLabel} upload) failed with status ${readBack.status}.`,
                'ERROR',
                [hl7Refs.binary],
            ),
        )
        return { validations, succeeded: false }
    }

    validations.push(
        validation(
            `Round-trip read-back succeeded for the ${mechanismLabel} upload: GET ${readBack.exchange.request.url} returned 200 OK`,
            'OK',
        ),
    )
    const readBackTyped = asTyped<Binary>(readBack.body, 'Binary')
    if (readBackTyped) {
        validations.push(...validateBinary(readBackTyped, { id: createdId, contentType: 'application/pdf' }))
    }

    return { validations, succeeded: true }
}

