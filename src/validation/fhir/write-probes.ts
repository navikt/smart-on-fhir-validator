/** Per bundle.md: `entry.request` uses `PUT` with the client-assigned sykmelding id. */
function buildBatchBundle(launch: LaunchContext, sykmeldingId: string): Bundle {
    const documentReference: DocumentReference = {
        ...buildInlineDocumentReference(launch),
        id: sykmeldingId,
        context: {
            encounter: [{ reference: `Encounter/${launch.encounterId}` }],
            related: [{ reference: `QuestionnaireResponse/${sykmeldingId}` }],
        },
    }
    const questionnaireResponse: QuestionnaireResponse = {
        ...buildQuestionnaireResponse(launch),
        id: sykmeldingId,
    }

    return {
        resourceType: 'Bundle',
        type: REQUIRED_BATCH_BUNDLE_TYPE,
        entry: [
            {
                fullUrl: `QuestionnaireResponse/${sykmeldingId}`,
                resource: questionnaireResponse,
                request: { method: 'PUT', url: `QuestionnaireResponse/${sykmeldingId}` },
            },
            {
                fullUrl: `DocumentReference/${sykmeldingId}`,
                resource: documentReference,
                request: { method: 'PUT', url: `DocumentReference/${sykmeldingId}` },
            },
        ],
    }
}

export const documentReferenceInlineWriteProbe: ResourceProbe = {
    id: 'document-reference-write-inline',
    label: 'Write DocumentReference with inline base64 PDF via idempotent PUT (mechanism 1)',
    required: true,
    async run(context: ProbeContext): Promise<ProbeOutcome> {
        const { fhir, launch } = context
        if (launch.patientId == null || launch.encounterId == null) {
            return skipped(
                documentReferenceInlineWriteProbe,
                'Launch context is missing a patient or encounter id, so a DocumentReference cannot be filed against a consultation.',
            )
        }

        const sykmeldingId = testId('docref-inline')
        const payload = { ...buildInlineDocumentReference(launch), id: sykmeldingId }
        const first = await fhir.update('DocumentReference', sykmeldingId, payload)

        if (!grantsWriteScope(launch, 'DocumentReference')) {
            return scopeEnforcementOutcome(
                documentReferenceInlineWriteProbe,
                first,
                'DocumentReference',
                launch,
                'PUT',
            )
        }

        const validations = upsertOutcomeValidations(first, 'DocumentReference', 'first')

        if (!first.ok) {
            return {
                probeId: documentReferenceInlineWriteProbe.id,
                label: documentReferenceInlineWriteProbe.label,
                exchangeId: first.exchange.id,
                validations,
            }
        }

        validations.push(testResourceNotice('DocumentReference', sykmeldingId))
        validations.push(
            ...validateDocumentReference(asTyped<DocumentReference>(first.body, 'DocumentReference'), {
                id: sykmeldingId,
                patientId: launch.patientId,
                encounterId: launch.encounterId,
                practitionerId: launch.practitionerId,
            }),
        )

        const second = await fhir.update('DocumentReference', sykmeldingId, payload)
        validations.push(...upsertOutcomeValidations(second, 'DocumentReference', 'second'))
        if (second.ok) {
            validations.push(idempotencyValidation(first, second, 'DocumentReference', sykmeldingId))
        }

        const readBack = await fhir.read('DocumentReference', sykmeldingId)
        if (!readBack.ok) {
            validations.push(
                validation(
                    `GET ${readBack.exchange.request.url} (round-trip read-back) failed with status ${readBack.status}. The server accepted the write but the resource cannot be read back.`,
                    'ERROR',
                    [hl7Refs.documentReference],
                ),
            )
        } else {
            validations.push(
                validation(
                    `Round-trip read-back succeeded: GET ${readBack.exchange.request.url} returned 200 OK`,
                    'OK',
                ),
            )
            validations.push(
                ...validateDocumentReference(asTyped<DocumentReference>(readBack.body, 'DocumentReference'), {
                    id: sykmeldingId,
                    patientId: launch.patientId,
                    encounterId: launch.encounterId,
                    practitionerId: launch.practitionerId,
                }),
            )
        }

        validations.push(
            ...(await searchableValidations(
                context,
                'DocumentReference',
                sykmeldingId,
                { subject: `Patient/${launch.patientId}` },
                '"subject" (GET [base]/DocumentReference?subject=Patient/{id})',
            )),
        )
        validations.push(
            ...(await searchableValidations(
                context,
                'DocumentReference',
                sykmeldingId,
                { encounter: `Encounter/${launch.encounterId}` },
                '"encounter" (GET [base]/DocumentReference?encounter=Encounter/{id})',
            )),
        )

        return {
            probeId: documentReferenceInlineWriteProbe.id,
            label: documentReferenceInlineWriteProbe.label,
            exchangeId: first.exchange.id,
            validations,
        }
    },
}

export const documentReferenceBinaryWriteProbe: ResourceProbe = {
    id: 'document-reference-write-binary',
    label: 'Write Binary then DocumentReference referencing it via idempotent PUT (mechanism 2)',
    required: true,
    async run(context: ProbeContext): Promise<ProbeOutcome> {
        const { fhir, launch } = context
        if (launch.patientId == null || launch.encounterId == null) {
            return skipped(
                documentReferenceBinaryWriteProbe,
                'Launch context is missing a patient or encounter id, so a DocumentReference cannot be filed against a consultation.',
            )
        }

        const sykmeldingId = testId('docref-binary')

        if (!grantsWriteScope(launch, 'DocumentReference')) {
            const response = await fhir.update('DocumentReference', sykmeldingId, {
                ...buildInlineDocumentReference(launch),
                id: sykmeldingId,
            })
            return scopeEnforcementOutcome(
                documentReferenceBinaryWriteProbe,
                response,
                'DocumentReference',
                launch,
                'PUT',
            )
        }

        const binaryResponse = await fhir.create('Binary', buildBinary())
        const validations = createOutcomeValidations(binaryResponse, 'Binary')
        const binaryId = extractCreatedId(binaryResponse)

        if (binaryId == null) {
            validations.push(
                validation(
                    'Could not determine the id of the created Binary, so the Binary-reference DocumentReference mechanism could not be tested.',
                    'ERROR',
                    [hl7Refs.binary],
                ),
            )
            return {
                probeId: documentReferenceBinaryWriteProbe.id,
                label: documentReferenceBinaryWriteProbe.label,
                exchangeId: binaryResponse.exchange.id,
                validations,
            }
        }
        validations.push(testResourceNotice('Binary', binaryId))

        const payload = { ...buildDocumentReferenceForBinary(launch, binaryId), id: sykmeldingId }
        const first = await fhir.update('DocumentReference', sykmeldingId, payload)
        validations.push(...upsertOutcomeValidations(first, 'DocumentReference', 'first'))

        if (!first.ok) {
            return {
                probeId: documentReferenceBinaryWriteProbe.id,
                label: documentReferenceBinaryWriteProbe.label,
                exchangeId: first.exchange.id,
                validations,
            }
        }
        validations.push(testResourceNotice('DocumentReference', sykmeldingId))
        validations.push(
            ...validateDocumentReference(asTyped<DocumentReference>(first.body, 'DocumentReference'), {
                id: sykmeldingId,
                patientId: launch.patientId,
                encounterId: launch.encounterId,
                practitionerId: launch.practitionerId,
            }),
        )

        const second = await fhir.update('DocumentReference', sykmeldingId, payload)
        validations.push(...upsertOutcomeValidations(second, 'DocumentReference', 'second'))
        if (second.ok) {
            validations.push(idempotencyValidation(first, second, 'DocumentReference', sykmeldingId))
        }

        const readBack = await fhir.read('DocumentReference', sykmeldingId)
        if (!readBack.ok) {
            validations.push(
                validation(
                    `GET ${readBack.exchange.request.url} (round-trip read-back) failed with status ${readBack.status}.`,
                    'ERROR',
                    [hl7Refs.documentReference],
                ),
            )
        } else {
            const readDoc = asTyped<DocumentReference>(readBack.body, 'DocumentReference')
            const url = readDoc?.content?.[0]?.attachment.url
            if (url != null && url.includes(binaryId)) {
                validations.push(
                    validation(
                        `Round-trip read-back preserved the Binary reference: content[0].attachment.url = "${url}"`,
                        'OK',
                    ),
                )
            } else {
                validations.push(
                    validation(
                        `Round-trip read-back did not preserve the Binary reference; content[0].attachment.url was "${url ?? 'missing'}", expected it to contain "${binaryId}". The server may have inlined or dropped the reference.`,
                        'ERROR',
                        [hl7Refs.documentReference],
                    ),
                )
            }
        }

        return {
            probeId: documentReferenceBinaryWriteProbe.id,
            label: documentReferenceBinaryWriteProbe.label,
            exchangeId: first.exchange.id,
            validations,
        }
    },
}

export const binaryWriteProbe: ResourceProbe = {
    id: 'binary-write',
    label: 'Write Binary via FHIR-JSON POST and raw-body POST',
    required: true,
    async run({ fhir, launch }: ProbeContext): Promise<ProbeOutcome> {
        const jsonResponse = await fhir.create('Binary', buildBinary())

        if (!grantsWriteScope(launch, 'Binary')) {
            return scopeEnforcementOutcome(binaryWriteProbe, jsonResponse, 'Binary', launch)
        }

        const jsonOutcome = await binaryMechanismValidations(
            fhir,
            jsonResponse,
            'FHIR-JSON POST (resourceType: "Binary")',
        )

        const rawResponse = await fhir.createBinaryRaw('application/pdf', TEST_PDF_BYTES)
        const rawOutcome = await binaryMechanismValidations(
            fhir,
            rawResponse,
            'raw-body POST (HTTP Content-Type: application/pdf)',
        )

        const validations = [...jsonOutcome.validations, ...rawOutcome.validations]

        if (jsonOutcome.succeeded && rawOutcome.succeeded) {
            validations.push(
                validation(
                    'Both Binary upload mechanisms (FHIR-JSON POST and raw-body POST) succeeded. Nav can write a Binary using either mechanism.',
                    'OK',
                    [navRefs.binary],
                ),
            )
        } else if (jsonOutcome.succeeded || rawOutcome.succeeded) {
            const working = jsonOutcome.succeeded ? 'FHIR-JSON POST' : 'raw-body POST'
            const failing = jsonOutcome.succeeded ? 'raw-body POST' : 'FHIR-JSON POST'
            validations.push(
                validation(
                    `Only the ${working} Binary upload mechanism succeeded; the ${failing} mechanism failed. Nav requires Binary write support (nav-requirements.md, "Må") but does not mandate a specific upload mechanism, so this alone is not fatal. The vendor should confirm their integration with Nav will use ${working}.`,
                    'WARNING',
                    [navRefs.binary],
                ),
            )
        } else {
            validations.push(
                validation(
                    'Both Binary upload mechanisms (FHIR-JSON POST and raw-body POST) failed. Nav requires Binary write support (nav-requirements.md, "Må"); a server supporting neither mechanism cannot receive the sykmelding PDF via Binary at all.',
                    'ERROR',
                    [navRefs.binary],
                ),
            )
        }

        return {
            probeId: binaryWriteProbe.id,
            label: binaryWriteProbe.label,
            exchangeId: jsonResponse.exchange.id,
            validations,
        }
    },
}

export const questionnaireResponseWriteProbe: ResourceProbe = {
    id: 'questionnaire-response-write',
    label: 'Write QuestionnaireResponse via idempotent PUT (optional per ADR01)',
    required: false,
    async run(context: ProbeContext): Promise<ProbeOutcome> {
        const { fhir, launch } = context
        if (launch.patientId == null || launch.encounterId == null) {
            return skipped(
                questionnaireResponseWriteProbe,
                'Launch context is missing a patient or encounter id, so a QuestionnaireResponse cannot be linked to a consultation.',
            )
        }

        const sykmeldingId = testId('qr')
        const payload = { ...buildQuestionnaireResponse(launch), id: sykmeldingId }
        const first = await fhir.update('QuestionnaireResponse', sykmeldingId, payload)

        if (!grantsWriteScope(launch, 'QuestionnaireResponse')) {
            return scopeEnforcementOutcome(
                questionnaireResponseWriteProbe,
                first,
                'QuestionnaireResponse',
                launch,
                'PUT',
            )
        }

        const validations = upsertOutcomeValidations(first, 'QuestionnaireResponse', 'first')

        if (!first.ok) {
            return {
                probeId: questionnaireResponseWriteProbe.id,
                label: questionnaireResponseWriteProbe.label,
                exchangeId: first.exchange.id,
                validations,
            }
        }

        validations.push(testResourceNotice('QuestionnaireResponse', sykmeldingId))
        validations.push(
            ...validateQuestionnaireResponse(
                asTyped<QuestionnaireResponse>(first.body, 'QuestionnaireResponse'),
                {
                    id: sykmeldingId,
                    patientId: launch.patientId,
                    encounterId: launch.encounterId,
                    practitionerId: launch.practitionerId,
                },
            ),
        )

        const second = await fhir.update('QuestionnaireResponse', sykmeldingId, payload)
        validations.push(...upsertOutcomeValidations(second, 'QuestionnaireResponse', 'second'))
        if (second.ok) {
            validations.push(idempotencyValidation(first, second, 'QuestionnaireResponse', sykmeldingId))
        }

        validations.push(
            ...(await searchableValidations(
                context,
                'QuestionnaireResponse',
                sykmeldingId,
                { subject: `Patient/${launch.patientId}` },
                '"subject" (GET [base]/QuestionnaireResponse?subject=Patient/{id})',
            )),
        )
        validations.push(
            ...(await searchableValidations(
                context,
                'QuestionnaireResponse',
                sykmeldingId,
                { encounter: `Encounter/${launch.encounterId}` },
                '"encounter" (GET [base]/QuestionnaireResponse?encounter=Encounter/{id})',
            )),
        )

        return {
            probeId: questionnaireResponseWriteProbe.id,
            label: questionnaireResponseWriteProbe.label,
            exchangeId: first.exchange.id,
            validations,
        }
    },
}

export const bundleBatchWriteProbe: ResourceProbe = {
    id: 'bundle-batch-write',
    label: 'Submit a batch Bundle with DocumentReference + QuestionnaireResponse (optional per ADR01)',
    required: false,
    async run({ fhir, launch }: ProbeContext): Promise<ProbeOutcome> {
        if (launch.patientId == null || launch.encounterId == null) {
            return skipped(
                bundleBatchWriteProbe,
                'Launch context is missing a patient or encounter id, so a batch Bundle cannot be constructed.',
            )
        }

        const hasDocRefScope = grantsWriteScope(launch, 'DocumentReference')
        const hasQrScope = grantsWriteScope(launch, 'QuestionnaireResponse')
        if (!hasDocRefScope || !hasQrScope) {
            const missing = [
                !hasDocRefScope ? 'DocumentReference' : null,
                !hasQrScope ? 'QuestionnaireResponse' : null,
            ]
                .filter((value): value is string => value != null)
                .join(' and ')
            return skipped(
                bundleBatchWriteProbe,
                `Granted scopes (${grantedScopesText(launch)}) do not include write access to ${missing}, required for both entries in the batch. Scope enforcement for each resource type individually is already covered by the standalone write probes.`,
            )
        }

        const sykmeldingId = testId('batch')
        const bundle = buildBatchBundle(launch, sykmeldingId)

        const validations = validateBatchBundleRequest(bundle)
        const response = await fhir.submitBundle(bundle)
        const url = response.exchange.request.url

        if (!response.ok) {
            const outcomeSummary = operationOutcomeSummary(response.body)
            validations.push(
                validation(
                    `POST ${url} (batch Bundle) failed with status ${response.status}. ${outcomeSummary ? `Server returned: ${outcomeSummary}` : 'No OperationOutcome was returned.'}`,
                    'ERROR',
                    [hl7Refs.bundleTransaction],
                ),
            )
            return {
                probeId: bundleBatchWriteProbe.id,
                label: bundleBatchWriteProbe.label,
                exchangeId: response.exchange.id,
                validations,
            }
        }

        validations.push(testResourceNotice('QuestionnaireResponse', sykmeldingId))
        validations.push(testResourceNotice('DocumentReference', sykmeldingId))
        validations.push(
            ...validateBatchBundleResponse(
                asTyped<Bundle>(response.body, 'Bundle'),
                bundle.entry?.length ?? 0,
            ),
        )

        return {
            probeId: bundleBatchWriteProbe.id,
            label: bundleBatchWriteProbe.label,
            exchangeId: response.exchange.id,
            validations,
        }
    },
}

